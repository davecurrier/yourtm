/**
 * Wrangler Configuration Template
 *
 * Generates wrangler.toml configuration for deploying the YourTM worker
 * to a user's Cloudflare account.
 */

export interface WranglerConfig {
  /** Worker name - defaults to "yourtm-worker" */
  name?: string;
  /** Main entry point - defaults to "worker.js" */
  main?: string;
  /** Compatibility date for Cloudflare Workers */
  compatibilityDate?: string;
  /** KV namespace ID for bundle storage */
  kvNamespaceId: string;
  /** Optional KV namespace ID for preview bundles */
  previewKvNamespaceId?: string;
  /** Account ID (optional, can be set via env or wrangler login) */
  accountId?: string;
  /** Custom routes to attach the worker to */
  routes?: Array<{
    pattern: string;
    zoneId?: string;
    zoneName?: string;
  }>;
  /** Environment variables to set */
  vars?: Record<string, string>;
  /** Secrets (names only - values set via wrangler secret) */
  secrets?: string[];
  /** Enable workers.dev subdomain */
  workersDevEnabled?: boolean;
  /** Custom domain for the worker */
  customDomain?: string;
  /** Environment-specific configurations */
  environments?: {
    staging?: Partial<WranglerConfig>;
    production?: Partial<WranglerConfig>;
  };
  /** Enable RUM (Real User Monitoring) with Durable Objects */
  enableRUM?: boolean;
  /** Analytics Engine dataset name for historical telemetry */
  analyticsDataset?: string;
}

/**
 * Generate wrangler.toml content
 */
export function generateWranglerConfig(config: WranglerConfig): string {
  const {
    name = 'yourtm-worker',
    main = 'worker.js',
    compatibilityDate = '2024-01-01',
    kvNamespaceId,
    previewKvNamespaceId,
    accountId,
    routes = [],
    vars = {},
    secrets = [],
    workersDevEnabled = true,
    customDomain,
    environments,
    enableRUM = true,
    analyticsDataset,
  } = config;

  const lines: string[] = [
    '# YourTM Cloudflare Worker Configuration',
    '# Generated by YourTM CLI',
    '# Docs: https://developers.cloudflare.com/workers/wrangler/configuration/',
    '',
    `name = "${name}"`,
    `main = "${main}"`,
    `compatibility_date = "${compatibilityDate}"`,
    '',
  ];

  // Account ID (optional)
  if (accountId) {
    lines.push(`account_id = "${accountId}"`);
    lines.push('');
  }

  // Workers.dev setting
  lines.push(`workers_dev = ${workersDevEnabled}`);
  lines.push('');

  // KV Namespace bindings
  lines.push('# KV Namespace for YourTM bundles');
  lines.push('[[kv_namespaces]]');
  lines.push('binding = "YTM_KV"');
  lines.push(`id = "${kvNamespaceId}"`);
  if (previewKvNamespaceId) {
    lines.push(`preview_id = "${previewKvNamespaceId}"`);
  }
  lines.push('');

  // RUM Durable Object bindings
  if (enableRUM) {
    lines.push('# RUM (Real User Monitoring) Durable Object');
    lines.push('# Handles real-time telemetry streaming and aggregation');
    lines.push('[[durable_objects.bindings]]');
    lines.push('name = "YTM_RUM"');
    lines.push('class_name = "RUMDurableObject"');
    lines.push('');
    lines.push('[[migrations]]');
    lines.push('tag = "v1"');
    lines.push('new_classes = ["RUMDurableObject"]');
    lines.push('');
  }

  // Analytics Engine bindings
  if (analyticsDataset) {
    lines.push('# Analytics Engine for historical telemetry data');
    lines.push('[[analytics_engine_datasets]]');
    lines.push('binding = "YTM_ANALYTICS"');
    lines.push(`dataset = "${analyticsDataset}"`);
    lines.push('');
  }

  // Routes
  if (routes.length > 0) {
    lines.push('# Routes');
    for (const route of routes) {
      lines.push('[[routes]]');
      // Ensure the pattern ends with /_ytm/* to avoid proxying all assets
      const safePattern = route.pattern.includes('/_ytm/*') 
        ? route.pattern 
        : (route.pattern.endsWith('/*') ? route.pattern.slice(0, -2) : route.pattern) + '/_ytm/*';
      lines.push(`pattern = "${safePattern}"`);
      if (route.zoneId) {
        lines.push(`zone_id = "${route.zoneId}"`);
      } else if (route.zoneName) {
        lines.push(`zone_name = "${route.zoneName}"`);
      }
      lines.push('');
    }
  }

  // Custom domain
  if (customDomain) {
    lines.push('# Custom Domain');
    lines.push('[[routes]]');
    const safeDomain = customDomain.endsWith('/') ? customDomain.slice(0, -1) : customDomain;
    lines.push(`pattern = "${safeDomain}/_ytm/*"`);
    lines.push('custom_domain = true');
    lines.push('');
  }

  // Environment variables
  if (Object.keys(vars).length > 0) {
    lines.push('# Environment Variables');
    lines.push('[vars]');
    for (const [key, value] of Object.entries(vars)) {
      lines.push(`${key} = "${value}"`);
    }
    lines.push('');
  }

  // Secrets comment
  if (secrets.length > 0) {
    lines.push('# Secrets (set via: wrangler secret put <name>)');
    lines.push(`# Required secrets: ${secrets.join(', ')}`);
    lines.push('');
  }

  // Staging environment
  if (environments?.staging) {
    lines.push('# Staging Environment');
    lines.push('[env.staging]');
    if (environments.staging.name) {
      lines.push(`name = "${environments.staging.name}"`);
    }
    if (environments.staging.kvNamespaceId) {
      lines.push('[[env.staging.kv_namespaces]]');
      lines.push('binding = "YTM_KV"');
      lines.push(`id = "${environments.staging.kvNamespaceId}"`);
    }
    if (environments.staging.vars) {
      lines.push('[env.staging.vars]');
      for (const [key, value] of Object.entries(environments.staging.vars)) {
        lines.push(`${key} = "${value}"`);
      }
    }
    lines.push('');
  }

  // Production environment
  if (environments?.production) {
    lines.push('# Production Environment');
    lines.push('[env.production]');
    if (environments.production.name) {
      lines.push(`name = "${environments.production.name}"`);
    }
    if (environments.production.kvNamespaceId) {
      lines.push('[[env.production.kv_namespaces]]');
      lines.push('binding = "YTM_KV"');
      lines.push(`id = "${environments.production.kvNamespaceId}"`);
    }
    if (environments.production.vars) {
      lines.push('[env.production.vars]');
      for (const [key, value] of Object.entries(environments.production.vars)) {
        lines.push(`${key} = "${value}"`);
      }
    }
    if (environments.production.routes) {
      for (const route of environments.production.routes) {
        lines.push('[[env.production.routes]]');
        lines.push(`pattern = "${route.pattern}"`);
        if (route.zoneId) {
          lines.push(`zone_id = "${route.zoneId}"`);
        } else if (route.zoneName) {
          lines.push(`zone_name = "${route.zoneName}"`);
        }
      }
    }
    lines.push('');
  }

  // Build configuration
  lines.push('# Build Configuration');
  lines.push('[build]');
  lines.push('command = "npm run build:worker"');
  lines.push('');

  // Observability
  lines.push('# Observability');
  lines.push('[observability]');
  lines.push('enabled = true');
  lines.push('');

  return lines.join('\n');
}

/**
 * Generate a minimal wrangler.toml for quick setup
 */
export function generateMinimalWranglerConfig(kvNamespaceId: string): string {
  return `# YourTM Cloudflare Worker Configuration
# Quick setup - customize as needed

name = "yourtm-worker"
main = "worker.js"
compatibility_date = "2024-01-01"

[[kv_namespaces]]
binding = "YTM_KV"
id = "${kvNamespaceId}"
`;
}

